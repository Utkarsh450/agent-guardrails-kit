import { spawnSync } from "node:child_process";
import { applyPlan } from "../../shared/fs-plan.ts";
import { HOOKS_DIR, isHooksPathConfigured } from "../git/index.ts";
import type { PlanEntry, SetupPlan } from "./types.ts";

export type Bucket = "create" | "update" | "unchanged" | "kept" | "conflict";

/** Groups plan entries for display. A hand-edited file the kit will not touch is "kept", a damaged one is "conflict". */
export function bucketOf(entry: PlanEntry): Bucket {
  const { file } = entry;
  if (file.status !== "conflict") return file.status;
  return file.reason?.includes("was not generated by agent-guardrails") ? "kept" : "conflict";
}

export function countBuckets(plan: SetupPlan): Record<Bucket, number> {
  const counts: Record<Bucket, number> = { create: 0, update: 0, unchanged: 0, kept: 0, conflict: 0 };
  for (const entry of plan.entries) counts[bucketOf(entry)] += 1;
  return counts;
}

/** Writes every create and update in the plan. Conflicts and unchanged files are never touched. */
export function applySetup(root: string, plan: SetupPlan): Promise<string[]> {
  return applyPlan(root, plan.entries.map((entry) => entry.file));
}

function git(root: string, args: string[]) {
  const result = spawnSync("git", args, { cwd: root, encoding: "utf8" });
  return { code: result.status ?? 1, stdout: result.stdout ?? "", stderr: result.stderr ?? "" };
}

/** Asks git whether core.hooksPath is the kit's folder. Returns null when git cannot tell (not a repo, no git). */
export function readHooksPath(root: string): boolean | null {
  const result = git(root, ["config", "--local", "--get", "core.hooksPath"]);
  if (result.code === 0) return isHooksPathConfigured(`[core]\n\thooksPath = ${result.stdout.trim()}\n`);
  if (result.code === 1) return false; // the key is simply not set
  return null;
}

/** Runs `git config core.hooksPath .githooks` in the project. Only the person running the CLI does this. */
export function setHooksPath(root: string): { ok: boolean; message: string } {
  const result = git(root, ["config", "core.hooksPath", HOOKS_DIR]);
  return result.code === 0 ? { ok: true, message: `git config core.hooksPath ${HOOKS_DIR}` } : { ok: false, message: result.stderr.trim() || "git config failed" };
}
