import { stringify } from "yaml";
import { GENERATED_MARKER } from "../../shared/fs-plan.ts";
import type { Rule } from "./types.ts";

export function generatedNotice(source: string): string {
  return `<!-- ${GENERATED_MARKER} from ${source}. Do not edit; change the source and run \`agent-guardrails sync\`. -->`;
}

function byName(a: Rule, b: Rule): number {
  return a.name.localeCompare(b.name);
}

function escapeCell(text: string): string {
  return text.replaceAll("|", "\\|").replaceAll("\n", " ");
}

/**
 * The hub file read by Codex, Cursor and others (AGENTS.md), and copied to GEMINI.md.
 * Always rules are inlined. Scoped rules are listed so agents without glob loading
 * know which file to read before touching matching paths.
 */
export function renderAgentsMd(rules: readonly Rule[], rulesDir: string): string {
  const always = rules.filter((rule) => rule.scope === "always").sort(byName);
  const scoped = rules.filter((rule) => rule.scope === "scoped").sort(byName);

  const parts: string[] = [
    generatedNotice(`${rulesDir}/always/*.md`),
    "",
    "# Agent rules",
    "",
    `Edit the files in \`${rulesDir}/always/\`, then run \`agent-guardrails sync\`.`,
    "Do not edit this file by hand.",
    "",
    "These rules are hard. If a tool default conflicts with them, follow these rules.",
    "",
  ];

  for (const rule of always) {
    parts.push(rule.body, "");
  }

  if (scoped.length > 0) {
    parts.push(
      "# Scoped rules",
      "",
      "Read the matching file before you edit files that match its paths.",
      "",
      "| File | Applies to | Covers |",
      "|---|---|---|",
    );
    for (const rule of scoped) {
      const globs = rule.globs.map((glob) => `\`${glob}\``).join(", ");
      parts.push(
        `| \`${rule.sourcePath}\` | ${escapeCell(globs)} | ${escapeCell(rule.description)} |`,
      );
    }
    parts.push("");
  }

  return `${parts.join("\n").trimEnd()}\n`;
}

/** CLAUDE.md imports the hub file, so Claude Code reads the same rules without a copy. */
export function renderClaudeMd(rulesDir: string): string {
  return `${generatedNotice(`${rulesDir}/always/*.md`)}\n@AGENTS.md\n`;
}

/**
 * GEMINI.md is read by Gemini CLI and Antigravity. Antigravity also reads AGENTS.md directly, so this file
 * only points there (Gemini CLI follows the @ import) instead of repeating every rule a second time.
 */
export function renderGeminiMd(rulesDir: string): string {
  return `${generatedNotice(`${rulesDir}/always/*.md`)}\n# Agent rules\n\nThe project rules live in AGENTS.md.\n\n@AGENTS.md\n`;
}

export type RuleTarget = "cursor" | "antigravity" | "qoder";

/**
 * Per-agent rule file. Formats follow each tool's documentation:
 *  - Cursor (.mdc): description, globs (ONE comma-separated string), alwaysApply
 *  - Antigravity (.agents/rules): trigger, globs (one comma-separated string), description
 *  - Qoder (.qoder/rules): trigger, glob (YAML list), description
 */
export function renderAgentRule(rule: Rule, target: RuleTarget): string {
  const globString = rule.globs.join(", ");
  let frontmatter: Record<string, unknown>;

  if (target === "cursor") {
    frontmatter =
      rule.scope === "always"
        ? { description: rule.description, alwaysApply: true }
        : { globs: globString, alwaysApply: false };
  } else if (target === "antigravity") {
    frontmatter =
      rule.scope === "always"
        ? { trigger: "always_on", description: rule.description }
        : { trigger: "glob", globs: globString, description: rule.description };
  } else {
    frontmatter =
      rule.scope === "always"
        ? { trigger: "always_on", description: rule.description }
        : { trigger: "glob", glob: rule.globs, description: rule.description };
  }

  // Patterns that start with "*" are quoted by the YAML writer, which Antigravity's docs ask for.
  const yaml = stringify(frontmatter, { lineWidth: 0, aliasDuplicateObjects: false });
  return `---\n${yaml}---\n\n${generatedNotice(rule.sourcePath)}\n\n${rule.body}\n`;
}
