import { chmod, lstat, mkdir, readFile, realpath, writeFile } from "node:fs/promises";
import path from "node:path";

/**
 * Shared "plan, then write" helpers used by every feature that installs files.
 *
 * Safety properties (these mirror the rules the kit installs):
 *  - paths must stay inside the project root,
 *  - an existing file we did not generate is never overwritten (reported as a conflict),
 *  - symlinks are never written through,
 *  - nothing is ever deleted.
 */

export const GENERATED_MARKER = "agent-guardrails:generated";
const MARKER_SCAN_LENGTH = 2000;

export interface DesiredFile {
  /** Path relative to the project root, forward slashes. */
  path: string;
  content: string;
  /** True when the file is derived output that may be regenerated on later runs. */
  generated: boolean;
  /** Make the file executable (git hooks must be). Ignored on Windows. */
  executable?: boolean;
}

export type FileStatus = "create" | "update" | "unchanged" | "conflict";

export interface PlannedFile extends DesiredFile {
  status: FileStatus;
  /** Current content on disk (null when the file does not exist). */
  existing: string | null;
  /** Why the file is a conflict (null otherwise). */
  reason: string | null;
}

export type ExistingKind = "file" | "symlink" | "other";

export interface ExistingFile {
  kind: ExistingKind;
  content: string;
  /** Whether any execute bit is set. Undefined when unknown (Windows, in-memory tests). */
  executable?: boolean;
}

export type ReadExisting = (relPath: string) => Promise<ExistingFile | null>;

export function isGenerated(content: string): boolean {
  return content.slice(0, MARKER_SCAN_LENGTH).includes(GENERATED_MARKER);
}

/** Validates and normalizes a project-relative path. Throws on anything that could escape the root. */
export function normalizeRelPath(relPath: string): string {
  const slashed = relPath.replaceAll("\\", "/");
  if (slashed === "" || slashed.startsWith("/") || /^[a-zA-Z]:/.test(slashed)) {
    throw new Error(`Path must be relative to the project root: "${relPath}"`);
  }
  const normalized = path.posix.normalize(slashed);
  if (normalized === "." || normalized === ".." || normalized.startsWith("../")) {
    throw new Error(`Path must stay inside the project root: "${relPath}"`);
  }
  return normalized;
}

export async function planFiles(
  desired: readonly DesiredFile[],
  readExisting: ReadExisting,
): Promise<PlannedFile[]> {
  const seen = new Set<string>();
  const planned: PlannedFile[] = [];

  for (const file of desired) {
    const rel = normalizeRelPath(file.path);
    if (seen.has(rel)) {
      throw new Error(`Two outputs target the same file: ${rel}`);
    }
    seen.add(rel);

    const existing = await readExisting(rel);
    // What the kit writes is always LF. (Embedded files can arrive with CRLF when the source was checked out on Windows.)
    const base = { ...file, content: file.content.replaceAll("\r\n", "\n"), path: rel };

    if (existing === null) {
      planned.push({ ...base, status: "create", existing: null, reason: null });
    } else if (existing.kind === "symlink") {
      planned.push({
        ...base,
        status: "conflict",
        existing: null,
        reason: "is a symlink; the kit never writes through symlinks",
      });
    } else if (existing.kind === "other") {
      planned.push({
        ...base,
        status: "conflict",
        existing: null,
        reason: "exists and is not a regular file",
      });
    } else if (existing.content === base.content) {
      // Same text, but a hook that lost its execute bit must be fixed, so that counts as an update.
      const needsChmod = file.executable === true && existing.executable === false;
      planned.push({ ...base, status: needsChmod ? "update" : "unchanged", existing: existing.content, reason: null });
    } else if (file.generated && isGenerated(existing.content)) {
      planned.push({ ...base, status: "update", existing: existing.content, reason: null });
    } else {
      planned.push({
        ...base,
        status: "conflict",
        existing: existing.content,
        reason: "exists and was not generated by agent-guardrails",
      });
    }
  }

  return planned;
}

function isNotFound(error: unknown): boolean {
  return (
    typeof error === "object" &&
    error !== null &&
    "code" in error &&
    (error as { code?: string }).code === "ENOENT"
  );
}

export function diskReadExisting(root: string): ReadExisting {
  return async (relPath) => {
    const rel = normalizeRelPath(relPath);
    const abs = path.join(root, ...rel.split("/"));
    let info;
    try {
      info = await lstat(abs);
    } catch (error) {
      if (isNotFound(error)) return null;
      throw error;
    }
    if (info.isSymbolicLink()) return { kind: "symlink", content: "" };
    if (!info.isFile()) return { kind: "other", content: "" };
    return {
      kind: "file",
      // Line endings do not count. A Windows checkout (git core.autocrlf) turns LF into CRLF, and that must not make
      // every generated file look "out of date".
      content: (await readFile(abs, "utf8")).replaceAll("\r\n", "\n"),
      ...(process.platform === "win32" ? {} : { executable: (info.mode & 0o111) !== 0 }),
    };
  };
}

async function assertParentInsideRoot(rootReal: string, absDir: string): Promise<void> {
  let dir = absDir;
  for (;;) {
    try {
      const real = await realpath(dir);
      if (real !== rootReal && !real.startsWith(rootReal + path.sep)) {
        throw new Error(`Refusing to write outside the project folder: ${absDir}`);
      }
      return;
    } catch (error) {
      if (!isNotFound(error)) throw error;
      const parent = path.dirname(dir);
      if (parent === dir) throw error;
      dir = parent;
    }
  }
}

/**
 * Writes `create` and `update` entries. Conflicts and unchanged files are never touched.
 * Returns the relative paths that were written.
 */
export async function applyPlan(root: string, plan: readonly PlannedFile[]): Promise<string[]> {
  const rootReal = await realpath(root);
  const written: string[] = [];

  for (const file of plan) {
    if (file.status !== "create" && file.status !== "update") continue;
    const rel = normalizeRelPath(file.path);
    const abs = path.join(root, ...rel.split("/"));
    await assertParentInsideRoot(rootReal, path.dirname(abs));
    await mkdir(path.dirname(abs), { recursive: true });
    await writeFile(abs, file.content, "utf8");
    if (file.executable === true && process.platform !== "win32") await chmod(abs, 0o755);
    written.push(rel);
  }

  return written;
}
